-- Narrow glyphs take fewer columns so "1.5" or "36%" don't look gappy.
local WIDTH = { ["."] = 3, [":"] = 3, ["°"] = 4, [" "] = 3, ["1"] = 5 }

local M = {}

-- Width of s at the given cap height (7 dot rows).
function M.width(s, height)
    local p = height / 7
    local cols = 0
    for ch in s:upper():gmatch(utf8.charpattern) do cols = cols + (WIDTH[ch] or 5) + 1 end
    return math.max(cols - 1, 0) * p
end

-- Draw s with its baseline at y. ghost: alpha for unlit cells (0 = none),
-- which gives the faint full-grid look of a real LED panel.
function M.draw(cr, x, y, s, height, r, g, b, ghost)
    local p = height / 7
    local dr = p * 0.40
    local top = y - height + p / 2
    local lit, off = {}, {}
    for ch in s:upper():gmatch(utf8.charpattern) do
        local glyph = G[ch] or G[" "]
        local cw = WIDTH[ch] or 5
        for row = 1, 7 do
            local line = glyph[row]
            for col = 1, cw do
                local cx, cy = x + (col - 1) * p + p / 2, top + (row - 1) * p
                local t = (line:sub(col, col) == "#") and lit or off
                t[#t + 1] = cx
                t[#t + 1] = cy
            end
        end
        x = x + (cw + 1) * p
    end
    if ghost and ghost > 0 then
        cairo_set_source_rgba(cr, r, g, b, ghost)
        for i = 1, #off, 2 do
            cairo_new_sub_path(cr)
            cairo_arc(cr, off[i], off[i + 1], dr * 0.7, 0, 2 * math.pi)
        end
        cairo_fill(cr)
    end
    cairo_set_source_rgba(cr, r, g, b, 1)
    for i = 1, #lit, 2 do
        cairo_new_sub_path(cr)
        cairo_arc(cr, lit[i], lit[i + 1], dr, 0, 2 * math.pi)
    end
    cairo_fill(cr)
end

return M
